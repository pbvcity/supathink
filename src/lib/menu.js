function renderMenu(lines) {
  return [
    '「建议思考方法」(建议但可自选;选定后按超限思考协议第 2 条一行声明:「本轮采用 <方法名>」)',
    ...lines.map((l) => '- ' + l),
  ].join('\n');
}

